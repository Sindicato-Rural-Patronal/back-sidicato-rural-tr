// Os campos de pessoa, escritos uma vez e usados por `people` e
// `registrations` (e, na fase 2, por `unimed` e `admins`), cada um com o seu
// `from` (decisão 006, item 2).
//
// AS CHAVES SÃO CONTRATO: não se renomeia nem se reaproveita uma chave. Os
// rótulos dos campos que já saíam no CSV são os cabeçalhos de hoje.

type PersonFieldDef = {
    key: string;
    label: string;
    group: string;
    type: ExportFieldType;
    privacy: ExportPrivacy;
    weight?: number;
    value: (p: PersonExportRow, ctx: ExportFieldContext) => unknown;
};

function primaryProperty(p: PersonExportRow): ExportProperty | undefined {
    return p.properties.find(x => x.id === p.primaryPropertyId) ?? p.properties[0];
}

/** Uma coluna do endereço da propriedade principal. */
function addressField(
    key: string,
    header: string,
    pick: (a: ExportAddress) => unknown,
    type: ExportFieldType = 'text',
): PersonFieldDef {
    return {
        key,
        label: `Endereço: ${header}`,
        group: 'Endereço',
        type,
        privacy: 'pessoal',
        value: p => {
            const a = primaryProperty(p)?.address;
            return a ? pick(a) : null;
        },
    };
}

